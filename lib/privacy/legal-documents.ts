export function serializeLegalDocument(document: LegalDocument) {
  return [
    document.title,
    `Дата редакции: ${document.revisionDate}.`,
    ...document.sections.flatMap((section) => [
      section.title,
      ...section.paragraphs,
      ...(section.items?.map((item) => `- ${item}`) ?? []),
    ]),
  ].join("\n\n");
}

export const RFQ_CONSENT_CANONICAL_TEXT = serializeLegalDocument(
  RFQ_CONSENT_DOCUMENT,
);

export function hasCurrentRfqLegalVersions(input: {
  consentVersion: unknown;
  policyVersion: unknown;
}) {
  return input.consentVersion === RFQ_CONSENT_VERSION
    && input.policyVersion === RFQ_POLICY_VERSION;
}
