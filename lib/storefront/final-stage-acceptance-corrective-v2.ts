function normalizeSourceText(value: string) {
  return value
    .replace(/<[^>]+>/gu, " ")
    .replaceAll("&nbsp;", " ")
    .replace(/\s+/gu, " ")
    .trim();
}

function withoutTerminalPunctuation(value: string) {
  return value.replace(/[.!?]+$/u, "").trim();
}

function acceptedDescriptionCandidates(product: Product) {
  const normalizedName = withoutTerminalPunctuation(normalizeSourceText(product.name));
  return normalizeSourceText(product.description)
    .split(/(?<=[.!?])\s+/u)
    .map((sentence) => sentence.trim())
    .filter((sentence) => sentence.length >= 20)
    .filter((sentence) => withoutTerminalPunctuation(sentence) !== normalizedName)
    .filter((sentence) => !DESCRIPTION_BOILERPLATE.test(sentence))
    .filter((sentence) => !DESCRIPTION_NEGATIVE.test(sentence))
    .filter((sentence) => FEATURE_SIGNAL.test(sentence))
    .slice(0, 4)
    .map((sourceText): SourceFeatureCandidate => ({
      feature: withoutTerminalPunctuation(sourceText),
      source: "accepted_description",
      sourceText,
    }));
}

export function getSourceFeatureCandidates(
  product: Product,
): readonly SourceFeatureCandidate[] {
  if (product.keyFeatures.length > 0) {
    return [...new Set(product.keyFeatures.map((feature) => feature.trim()))]
      .filter(Boolean)
      .map((feature) => ({
        feature,
        source: "existing_approved_key_feature" as const,
        sourceText: feature,
      }));
  }
  if (product.id === COMEN_CM1200B_PRODUCT_ID) return CM1200B_FEATURES;
  const acceptedSummaries = ACCEPTED_DESCRIPTION_FEATURES[product.model];
  if (acceptedSummaries) {
    const description = normalizeSourceText(product.description);
    return acceptedSummaries.map(([feature, sourceText]) => {
      if (!description.includes(sourceText)) {
        throw new Error(
          `Final Stage acceptance rejected: source evidence drift for ${product.model}: ${sourceText}`,
        );
      }
      return {
        feature,
        source: "accepted_description" as const,
        sourceText,
      };
    });
  }
  return acceptedDescriptionCandidates(product);
}

export function applyFinalStageAcceptanceCorrectiveV2(
  stageCatalog: StorefrontCatalog,
  canonicalCatalog: StorefrontCatalog,
): StorefrontCatalog {
  if (stageCatalog.products.length !== FINAL_STAGE_ACCEPTANCE_PRODUCT_COUNT) {
    throw new Error(
      `Final Stage acceptance rejected: expected ${FINAL_STAGE_ACCEPTANCE_PRODUCT_COUNT} Products, received ${stageCatalog.products.length}`,
    );
  }

  const canonicalHamilton = canonicalCatalog.products.find(
    ({ id }) => id === HAMILTON_T1_PRODUCT_ID,
  );
  if (!canonicalHamilton || canonicalHamilton.model !== "Hamilton-T1") {
    throw new Error("Final Stage acceptance rejected: canonical Hamilton-T1 is absent");
  }

  const products = stageCatalog.products.map((product) => {
    const restored = product.id === HAMILTON_T1_PRODUCT_ID
      ? {
          ...product,
          shortDescription: canonicalHamilton.shortDescription,
          description: canonicalHamilton.description,
        }
      : product;
    const candidates = getSourceFeatureCandidates(restored);
    if (restored.keyFeatures.length > 0 || candidates.length === 0) return restored;
    return {
      ...restored,
      keyFeatures: candidates.map(({ feature }) => feature),
    };
  });
  return {
    ...stageCatalog,
    products,
  };
}
